
-- SPELERS
CREATE TABLE IF NOT EXISTS players (
  id SERIAL PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- SPEELDAGEN
CREATE TABLE IF NOT EXISTS matchdays (
  id SERIAL PRIMARY KEY,
  match_date DATE NOT NULL,
  location VARCHAR(200),
  registration_open BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- INSCHRIJVINGEN
CREATE TABLE IF NOT EXISTS registrations (
  id SERIAL PRIMARY KEY,
  matchday_id INTEGER NOT NULL REFERENCES matchdays(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  registered_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(matchday_id, player_id)
);

-- TEAMS
CREATE TABLE IF NOT EXISTS teams (
  id SERIAL PRIMARY KEY,
  matchday_id INTEGER NOT NULL REFERENCES matchdays(id) ON DELETE CASCADE,
  team_number INTEGER NOT NULL CHECK (team_number IN (1, 2)),
  UNIQUE(matchday_id, team_number)
);

-- SPELERS IN TEAMS
CREATE TABLE IF NOT EXISTS team_players (
  id SERIAL PRIMARY KEY,
  team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  UNIQUE(team_id, player_id)
);

-- WEDSTRIJDUITSLAGEN
CREATE TABLE IF NOT EXISTS match_results (
  id SERIAL PRIMARY KEY,
  matchday_id INTEGER NOT NULL UNIQUE REFERENCES matchdays(id) ON DELETE CASCADE,
  team1_score INTEGER NOT NULL DEFAULT 0,
  team2_score INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- PERSOONLIJKE WEDSTRIJDSTATISTIEKEN
CREATE TABLE IF NOT EXISTS player_match_stats (
  id SERIAL PRIMARY KEY,
  matchday_id INTEGER NOT NULL REFERENCES matchdays(id) ON DELETE CASCADE,
  player_id INTEGER NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  goals INTEGER NOT NULL DEFAULT 0,
  assists INTEGER NOT NULL DEFAULT 0,
  UNIQUE(matchday_id, player_id)
);
